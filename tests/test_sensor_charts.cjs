const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../static/js/dashboard.js'),'utf8');
const start=source.indexOf('  const sparks={};'),end=source.indexOf('  /* ---- gauge ---- */',start);
let strokes=0;const lines=[];
const context={clearRect(){},beginPath(){},moveTo(){},lineTo(x,y){lines.push([x,y]);},stroke(){strokes++;},arc(){},fill(){}};
const caption={classList:{contains:()=>true},textContent:''};
const canvas={clientWidth:200,clientHeight:54,getContext:()=>context,nextElementSibling:caption,setAttribute(){}};
const nodes={'sp-pt-temp':canvas,'sp-kt-gas':{}};
const sandbox={document:{getElementById:id=>nodes[id]||null,querySelectorAll:()=>[]},window:{devicePixelRatio:1},fetch:()=>Promise.resolve({ok:false}),Date};
vm.createContext(sandbox);vm.runInContext(source.slice(start,end),sandbox);
sandbox.renderSensorHistories({patient:{temp:[21,null,24],labels:['10:00','10:01','10:02']}});
assert.equal(lines.length,0,'missing readings break the line rather than becoming zero');
assert.ok(caption.textContent.includes('21')&&caption.textContent.includes('24'));
assert.ok(caption.textContent.includes('10:00'));
canvas.clientWidth=0;
sandbox.renderSensorHistories({patient:{temp:[22,23],labels:['11:00','11:01']}});
const before=strokes;canvas.clientWidth=200;sandbox.drawSpark('sp-pt-temp');
assert.equal(strokes,before+1,'hidden tab history is drawn after it becomes visible');
assert.ok(caption.textContent.includes('11:01'));
console.log('PASS: server history, missing readings, chart redraw after tab activation');
